export function buildDefaultCategoriesForCity(cityId: string): CategoryDoc[] {
  return FIXED_CATEGORIES.map((cat) => ({
    id: `${cityId}_${cat.category.toLowerCase()}`,
    cityId,
    category: cat.category,
    title: cat.title,
    subCategories: [...cat.defaultSubs],
  }));
}

